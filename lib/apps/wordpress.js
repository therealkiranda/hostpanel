'use strict';
// WordPress handler: WP-CLI downloads and verifies the core files (it checks WordPress.org's published checksum),
// HostPanel writes wp-config.php, WP-CLI runs the standard core install. Everything runs as the website's Linux
// user, and the administrator password only ever travels through stdin / a file with mode 600 - never argv.
const crypto = require('crypto');
const { validate: validateWp } = require('../wordpress-installer');
const { cleanSubdir } = require('./engine');

const LOCALES = [['en_US', 'English (US)'], ['en_GB', 'English (UK)'], ['en_AU', 'English (Australia)'], ['en_CA', 'English (Canada)'], ['ne_NP', 'Nepali'], ['hi_IN', 'Hindi'], ['bn_BD', 'Bengali'],
  ['es_ES', 'Spanish (Spain)'], ['es_MX', 'Spanish (Mexico)'], ['fr_FR', 'French'], ['de_DE', 'German'], ['it_IT', 'Italian'], ['pt_BR', 'Portuguese (Brazil)'], ['pt_PT', 'Portuguese (Portugal)'],
  ['nl_NL', 'Dutch'], ['sv_SE', 'Swedish'], ['pl_PL', 'Polish'], ['ru_RU', 'Russian'], ['tr_TR', 'Turkish'], ['ar', 'Arabic'], ['id_ID', 'Indonesian'], ['ja', 'Japanese'], ['ko_KR', 'Korean'], ['zh_CN', 'Chinese (Simplified)'], ['zh_TW', 'Chinese (Traditional)']];

function fields(env) {
  return [
    { name: 'title', label: 'Site title', type: 'text', value: '', placeholder: 'My Website', required: true },
    { name: 'adminUsername', label: 'Administrator username', type: 'text', value: '', placeholder: 'siteowner', required: true, pattern: '[A-Za-z][A-Za-z0-9_.-]{2,31}', hint: 'Not "admin" - it is the first name attackers try.' },
    { name: 'adminEmail', label: 'Administrator email', type: 'email', value: env.email || '', placeholder: 'you@example.com', required: true },
    { name: 'adminPassword', label: 'Administrator password', type: 'text', value: env.password || '', required: true, mono: true, hint: 'Generated for you - copy it now, HostPanel does not store it. Minimum 16 characters.' },
    { name: 'locale', label: 'Language', type: 'select', options: LOCALES, value: 'en_US' }
  ];
}

function validate(input) {
  const x = validateWp(input);                       // same rules as the standalone coordinator (domain, title, admin, locale)
  x.path = cleanSubdir(input.path);
  x.https = input.https === true || input.https === '1';
  return x;
}

const phpStr = (v) => "'" + String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const salt = () => crypto.randomBytes(48).toString('base64url');         // 64 chars of A-Za-z0-9_- : safe inside a PHP string
function wpConfig(db, x, prefix) {
  const keys = ['AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT'];
  return '<?php\n/** Generated by HostPanel. Edit with care. */\n' +
    "define( 'DB_NAME', " + phpStr(db.name) + ' );\ndefine( \'DB_USER\', ' + phpStr(db.user) + ' );\ndefine( \'DB_PASSWORD\', ' + phpStr(db.password) + ' );\n' +
    "define( 'DB_HOST', " + phpStr(db.host || 'localhost') + " );\ndefine( 'DB_CHARSET', 'utf8mb4' );\ndefine( 'DB_COLLATE', '' );\n\n" +
    keys.map((k) => "define( '" + k + "', " + phpStr(salt()) + ' );').join('\n') + '\n\n' +
    '$table_prefix = ' + phpStr(prefix) + ';\n\n' +
    "define( 'WP_DEBUG', false );\ndefine( 'DISALLOW_FILE_EDIT', true );\ndefine( 'FS_METHOD', 'direct' );\n" +
    (x.https ? "define( 'FORCE_SSL_ADMIN', true );\n" : '') +
    "\nif ( ! defined( 'ABSPATH' ) ) {\n\tdefine( 'ABSPATH', __DIR__ . '/' );\n}\n\nrequire_once ABSPATH . 'wp-settings.php';\n";
}

const SET_PASSWORD = "$u = get_user_by( 'login', getenv( 'HP_WP_ADMIN' ) ); if ( ! $u ) { fwrite( STDERR, \"Administrator not found\\n\" ); exit( 1 ); } " +
  'wp_set_password( rtrim( (string) fgets( STDIN ), "\r\n" ), $u->ID );';

async function install({ x, site, target, db, host, log }) {
  const wp = await host.ensureTool('wp-cli', log);
  const tmp = await host.makeTemp(site);
  try {
    const env = { HOME: tmp.abs, TMPDIR: tmp.abs, WP_CLI_CACHE_DIR: tmp.abs + '/cache', WP_CLI_PACKAGES_DIR: tmp.abs + '/packages', WP_CLI_DISABLE_AUTO_CHECK_UPDATE: '1' };
    const run = (args, o) => host.php(site, [wp, '--no-color', '--path=' + target.dir].concat(args), Object.assign({ env }, o || {}));
    log('Downloading WordPress (' + x.locale + ') - WP-CLI verifies the official checksum');
    await run(['core', 'download', '--locale=' + x.locale]);
    log('Writing wp-config.php');
    const prefix = 'wp' + crypto.randomBytes(2).toString('hex') + '_';
    await host.writeFile(site, target.rel + '/wp-config.php', wpConfig(db, x, prefix), '600');
    await host.php(site, ['-l', target.dir + '/wp-config.php'], { env });
    const url = (x.https ? 'https://' : 'http://') + x.domain + (x.path ? '/' + x.path : '');
    log('Running the WordPress installation for ' + url);
    // A random throw-away password is used here; the real one is applied next through stdin so it never appears in `ps`.
    await run(['core', 'install', '--url=' + url, '--title=' + x.title, '--admin_user=' + x.adminUsername, '--admin_email=' + x.adminEmail,
      '--admin_password=' + crypto.randomBytes(18).toString('base64url'), '--skip-email']);
    await run(['eval', SET_PASSWORD], { input: x.adminPassword + '\n', env: Object.assign({}, env, { HP_WP_ADMIN: x.adminUsername }) });
    let version = '';
    try { version = (/^\d+(?:\.\d+)+/m.exec(await run(['core', 'version'])) || [''])[0]; } catch (e) { /* cosmetic */ }
    try { await run(['rewrite', 'structure', '/%postname%/']); } catch (e) { log('Note: pretty permalinks were not set (' + String(e.message).slice(0, 120) + '). Set them in Settings > Permalinks.'); }
    log('WordPress' + (version ? ' ' + version : '') + ' is installed');
    return { url: url + '/', adminUrl: url + '/wp-admin/', meta: { version, url: url + '/', adminUrl: url + '/wp-admin/', adminUser: x.adminUsername } };
  } finally { await host.removeTemp(site, tmp).catch(() => {}); }
}

module.exports = { validate, install, fields, wpConfig, LOCALES, SET_PASSWORD };
